// One-time: lifts answer content out of the generated pages into
// content/answers/{en,fr}/*.md, so the repo holds the content rather than
// Supabase.
//
// Run: node scripts/export-content-files.mjs [--dry-run]
//
// The text comes from each page's FAQPage JSON-LD, whose acceptedAnswer.text
// is the original chunk text with its paragraph breaks and "- " bullets
// intact -- not from the rendered HTML, which would have to be un-rendered.
// scripts/reingest-from-pages.mjs proved that round-trips exactly: for all
// 1,204 English and 1,204 French answers, deriveQuestion(content) matches the
// page's <h1> and renderMarkdown of the remainder matches its short-answer
// markup, byte for byte.
//
// section_title (the Beginner/Intermediate difficulty label) is read from the
// commit before edfc0b2f stripped the meta-bar from answer pages. It is never
// translated, so the English page supplies it for both languages.
//
// Skipped: redirect stubs, and hand-authored pages with no generator marker
// (answer-grenache-alcohol-tannin.html) -- those were never chunks.

import { readdirSync, readFileSync, mkdtempSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { writeAnswerFile, CONTENT_DIR } from '../lib/content-files.mjs';

const DRY_RUN = process.argv.includes('--dry-run');
const META_BAR_COMMIT = '98400fd3';

const decode = (s) =>
  s
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&');

// Difficulty label per slug, from the last commit that still rendered it.
function difficultyBySlug() {
  const out = new Map();
  try {
    const dir = mkdtempSync(path.join(tmpdir(), 'tc-metabar-'));
    execFileSync('sh', ['-c', `git archive ${META_BAR_COMMIT} -- 'answer-*.html' | tar -x -C ${dir}`]);
    for (const file of readdirSync(dir).filter((f) => /^answer-.*\.html$/.test(f))) {
      const html = readFileSync(path.join(dir, file), 'utf8');
      const bar = html.match(/<div class="meta-bar">([\s\S]*?)<\/div>\s*<\/div>/);
      const difficulty = bar?.[1].match(/Difficulty<\/p><p class="v"><a[^>]*>([^<]*)</);
      if (difficulty) out.set(file.replace(/^answer-|\.html$/g, ''), decode(difficulty[1]).trim());
    }
  } catch (error) {
    console.warn(`  !! could not read ${META_BAR_COMMIT}: ${error.message}`);
    console.warn('     files will have no section_title');
  }
  return out;
}

const difficulty = difficultyBySlug();
const written = { en: 0, fr: 0 };
const skipped = [];

for (const [dir, lang] of [['.', 'en'], ['fr', 'fr']]) {
  for (const file of readdirSync(dir).filter((f) => /^answer-.*\.html$/.test(f))) {
    const html = readFileSync(path.join(dir, file), 'utf8');
    if (/Redirect stub/.test(html)) continue;
    if (!/Generated by/.test(html)) {
      skipped.push(`${dir === '.' ? '' : 'fr/'}${file} (hand-authored)`);
      continue;
    }
    const slug = file.replace(/^answer-|\.html$/g, '');

    let entity;
    try {
      entity = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]).mainEntity?.[0];
    } catch {
      skipped.push(`${file} (no usable JSON-LD)`);
      continue;
    }
    if (!entity?.name || !entity?.acceptedAnswer?.text) {
      skipped.push(`${file} (JSON-LD missing question or answer)`);
      continue;
    }

    const row = {
      source_doc: `qa-${slug}`,
      // qa-region-* rows are region-qa; everything else is qa.
      chunk_type: slug.startsWith('region-') ? 'region-qa' : 'qa',
      section_title: difficulty.get(slug) ?? null,
      question: entity.name,
      answer: entity.acceptedAnswer.text,
    };
    if (!DRY_RUN) writeAnswerFile(lang, row);
    written[lang]++;
  }
}

console.log(DRY_RUN ? 'DRY RUN — nothing written\n' : `wrote ${CONTENT_DIR}/\n`);
console.log(`  en: ${written.en}`);
console.log(`  fr: ${written.fr}`);
console.log(`  total: ${written.en + written.fr}`);
console.log(`  with a difficulty label: ${difficulty.size} slugs available`);
if (skipped.length) {
  console.log(`\nskipped ${skipped.length}:`);
  skipped.forEach((s) => console.log(`  ${s}`));
}
