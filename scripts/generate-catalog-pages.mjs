// English only for now: there are no fr/ catalog pages yet.
function fetchRows(applyFilter) {
  return fetchAllRows(() =>
    applyFilter(
      supabase
        .from('knowledge_chunks')
        .select('id, content, source_doc, section_title, chunk_type')
        .eq('status', 'published')
        .eq('lang', 'en')
    )
      .order('source_doc')
      .order('id')
  );
}

function groupBySourceDoc(rows) {
  const groups = new Map();
  for (const row of rows) {
    if (!groups.has(row.source_doc)) groups.set(row.source_doc, []);
    groups.get(row.source_doc).push(row);
  }
  return [...groups.entries()];
}

function humanizeSlug(slug) {
  return slug
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

// A grape/region row links to its topic page when one exists (exact
// source_doc match only -- same rule as resolveTopicSlug() in
// supabase-client.js); anything else opens the inline modal.
function linkAttrs(chunk) {
  const topic = TOPICS.find((t) => t.kind === chunk.chunk_type && t.sourceDoc === chunk.source_doc);
  if (topic) return `href="topic-${topic.slug}.html"`;
  return `href="#" onclick="window.KnowledgeBase.showChunkDetail(${escapeHtml(JSON.stringify(chunk))}); return false;"`;
}

function renderPage({ file, title, description, main, script = '' }) {
  return [
    renderHead({ title, description }),
    GENERATED_MARKER,
    renderHeader({ currentNav: file }),
    main,
    renderFooter(),
    '',
    `  <script src="supabase-client.js"></script>${script}
</body>
</html>
`,
  ].join('\n');
}

// --- grapes.html ------------------------------------------------------------
// Grapes means chunk_type='grape', section_title='Overview' -- the one
// canonical row per variety. Non-Overview 'grape' rows are sub-topics of a
// variety (e.g. "Grenache -- New World"), not separate grapes.
// Content shape: "{eyebrow}\n\n{name}\n\n{lede}\n\n{factsBlock}", with the
// country as the second "/"-separated part of the eyebrow.

async function buildGrapes() {
  const rows = await fetchRows((q) => q.eq('chunk_type', 'grape').eq('section_title', 'Overview'));
  const grapes = rows
    .map((row) => {
      const [eyebrow = '', name = ''] = row.content.split('\n\n');
      const grapeName = (name || row.source_doc.replace(/^grape-/, '')).trim();
      // The modal's title comes from section_title, which is literally
      // "Overview" on every one of these rows -- use the grape name instead.
      return { name: grapeName, country: eyebrow.split('/')[1]?.trim() || '', chunk: { ...row, section_title: grapeName } };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  if (grapes.length === 0) throw new Error('no grape Overview rows returned');

  const tiles = grapes
    .map(
      (g) => `        <a class="tile" data-name="${escapeHtml(g.name.toLowerCase())}" ${linkAttrs(g.chunk)}>
          <span class="name">${escapeHtml(g.name)}</span>
          <span class="n">${escapeHtml(g.country)}</span>
        </a>`
    )
    .join('\n');

  return renderPage({
    file: 'grapes.html',
    title: 'Grapes — Thirsty Cunt Knowledge Base',
    description: 'Every grape variety in the knowledge base, browsable by name.',
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="index.html">Home</a> / Grapes</p>
      <h1 class="page-title">All Grape Varieties</h1>
      <p class="lede sm">${grapes.length} varieties. Click one to see what we've written about it.</p>

      <input class="search-input" type="search" id="grapeSearch" placeholder="search grapes" aria-label="Search grapes" style="margin-bottom: 28px" />

      <p class="count" id="grapeCount">${grapes.length} grapes</p>
      <div id="grapesGrid" class="grid tiles">
${tiles}
      </div>
    </div>
  </main>`,
    // Filters the pre-rendered tiles in place.
    script: `
  <script>
    (() => {
      const input = document.getElementById('grapeSearch');
      const count = document.getElementById('grapeCount');
      const tiles = [...document.querySelectorAll('#grapesGrid .tile')];
      input.addEventListener('input', () => {
        const q = input.value.trim().toLowerCase();
        let shown = 0;
        for (const tile of tiles) {
          tile.hidden = Boolean(q) && !tile.dataset.name.includes(q);
          if (!tile.hidden) shown++;
        }
        count.textContent = shown === 0 ? 'No grapes match that search.' : \`\${shown} grape\${shown !== 1 ? 's' : ''}\`;
      });
    })();
  </script>`,
  });
}

// --- regions.html -----------------------------------------------------------
// chunk_type='region' isn't one row per browsable region -- it's ~35
// macro-region "chapters" (source_doc, e.g. "region-italy-central"), each
// holding section rows for its sub-regions (Chianti, Tuscany, ...). There's
// no per-country label stored anywhere, so group names come from the slug.

async function buildRegions() {
  const rows = await fetchRows((q) => q.eq('chunk_type', 'region'));
  const groups = groupBySourceDoc(rows)
    .map(([sourceDoc, groupRows]) => ({ name: humanizeSlug(sourceDoc.replace(/^region-/, '')), rows: groupRows }))
    .sort((a, b) => a.name.localeCompare(b.name));
  if (groups.length === 0) throw new Error('no region rows returned');

  // <details> keeps every sub-region in the HTML (crawlable) while still
  // collapsing each group, with no JavaScript needed.
  const sections = groups
    .map((group) => {
      const items = group.rows
        .map(
          (chunk) => `          <a class="row-item" ${linkAttrs(chunk)}>
            <span class="id">${escapeHtml(chunk.source_doc.toUpperCase())}</span>
            <span class="t">${escapeHtml(chunk.section_title || 'Untitled')}</span>
            <span class="k">${escapeHtml(chunk.chunk_type.toUpperCase())}</span>
          </a>`
        )
        .join('\n');
      return `        <details class="region-group">
          <summary class="list-head"><span>${escapeHtml(group.name)}</span><span>${group.rows.length}</span></summary>
${items}
        </details>`;
    })
    .join('\n');

  return renderPage({
    file: 'regions.html',
    title: 'Regions — Thirsty Cunt Knowledge Base',
    description: "Every wine region we've written about, grouped and browsable.",
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="index.html">Home</a> / Regions</p>
      <h1 class="page-title">Wine Regions</h1>
      <p class="lede sm">${groups.length} regions, ${rows.length} sub-topics between them. Expand one to browse.</p>

      <div>
${sections}
      </div>
    </div>
  </main>`,
  });
}

// --- guides.html ------------------------------------------------------------
// guide/comparison chunks come in 2-3 rows per source_doc ("Concept" +
// "Teaching", "Overview" + "Practice", ...). One card per source_doc, opening
// its first row in the modal -- 7 groups, not enough for detail pages.
// Titles come from source_doc: section_title suffixes are inconsistent.
// enology rows are excluded: they already have their own topic pages.

async function buildGuides() {
  const rows = await fetchRows((q) => q.in('chunk_type', ['guide', 'comparison']));
  const groups = groupBySourceDoc(rows).map(([sourceDoc, groupRows]) => ({
    title: humanizeSlug(sourceDoc.replace(/^(guide|comparison)-/, '')),
    rows: groupRows,
  }));
  if (groups.length === 0) throw new Error('no guide/comparison rows returned');

  const cards = groups
    .map((group) => {
      const primary = group.rows[0];
      const body = primary.content.split('\n\n').slice(1).join(' ').trim();
      const preview = body.length > 160 ? `${body.slice(0, 160)}…` : body;
      const chunk = { ...primary, section_title: group.title };
      return `        <a class="card topic" href="#" onclick="window.KnowledgeBase.showChunkDetail(${escapeHtml(JSON.stringify(chunk))}); return false;">
          <span class="card-meta">${escapeHtml(primary.chunk_type.toUpperCase())} &middot; ${group.rows.length} part${group.rows.length !== 1 ? 's' : ''}</span>
          <span class="card-title sm">${escapeHtml(group.title)}</span>
          <p>${escapeHtml(preview)}</p>
          <span class="more">Read &rarr;</span>
        </a>`;
    })
    .join('\n');

  return renderPage({
    file: 'guides.html',
    title: 'Guides — Thirsty Cunt Knowledge Base',
    description: 'How wine works, and how bottles compare, in longer form than a single answer.',
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="index.html">Home</a> / Guides</p>
      <h1 class="page-title">Guides &amp; Comparisons</h1>
      <p class="lede sm">${groups.length} guides and comparisons, ${rows.length} parts in total.</p>

      <div class="grid answers-3">
${cards}
      </div>
    </div>
  </main>`,
  });
}

const builds = [
  ['grapes.html', buildGrapes],
  ['regions.html', buildRegions],
  ['guides.html', buildGuides],
];

let failed = 0;
for (const [file, build] of builds) {
  try {
    writeFileSync(file, await build());
    console.log(`  -> ${file}`);
  } catch (error) {
    console.error(`  !! ${file}: ${error.message} -- kept the existing file`);
    failed++;
  }
}
if (failed) process.exitCode = 1;
