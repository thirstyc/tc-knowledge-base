// Generates the three browse pages -- grapes.html, regions.html and
// guides.html -- pre-rendered from knowledge_chunks, so crawlers that don't
// run JavaScript see the full catalog instead of a "Loading…" shell.
//
// Run: node scripts/generate-catalog-pages.mjs   (or npm run generate:catalogs)
//
// If a catalog's fetch fails or comes back empty (there are always 180+
// grapes, ~35 region groups and 7 guides, so empty means the request
// failed), that page keeps its existing file and the script exits 1.

