// A few guide bodies (e.g. "How To Taste Wine") are written as a numbered
// Markdown list with **bold** step names -- fine in the full guide, but
// the card preview here just wants a plain-text snippet, not raw
// "1. **Look** — ..." syntax.
function stripMarkdown(text) {
  return text
    .replace(/^\s*(?:\d+\.|-)\s+/gm, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\s*\n\s*/g, '; ')
    .trim();
}

function groupNameFr(strippedSlug) {
  return REGION_GROUP_NAMES_FR[strippedSlug] ?? humanizeSlug(strippedSlug);
}

function guideTitleFr(strippedSlug) {
  return GUIDE_TITLES_FR[strippedSlug] ?? humanizeSlug(strippedSlug);
}

// Where a grape/region row lives (mirrored by chunkHref() in
// supabase-client.js). hrefs are plain same-directory filenames: English
// and French catalog pages each sit next to their own language's pages.
//   - a source_doc with a topic page: that topic page (grape Overview rows,
//     and the Overview row of the six region topics)
//   - any other grape: its own grape-*.html page
//   - a region section: its region-*.html page, at that section's anchor
function topicFor(chunk) {
  return TOPICS.find((t) => t.kind === chunk.chunk_type && t.sourceDoc === chunk.source_doc);
}

function linkAttrs(href) {
  return `href="${href}"`;
}

function hreflangAlternates(file) {
  return [
    { hreflang: 'en', href: `${BASE_URL}/${file}` },
    { hreflang: 'fr', href: `${BASE_URL}/fr/${file}` },
    { hreflang: 'x-default', href: `${BASE_URL}/${file}` },
  ];
}

// nav is the header item to highlight; defaults to the page itself.
function renderPage({ file, nav = file, title, description, main, script = '', lang, jsonLd = [] }) {
  const ap = assetPrefixFor(lang);
  const isFr = lang === 'fr';
  return [
    renderHead({ title, description, lang, assetPrefix: ap, alternates: hreflangAlternates(file), jsonLd }),
    GENERATED_MARKER,
    renderHeader({
      currentNav: nav,
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${file}`,
      enHref: isFr ? `../${file}` : null,
    }),
    main,
    renderFooter({
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${file}`,
      enHref: isFr ? `../${file}` : null,
    }),
    '',
    `  <script src="${ap}supabase-client.js"></script>${script}
</body>
</html>
`,
  ].join('\n');
}

// --- grapes.html ------------------------------------------------------------
// Grapes means chunk_type='grape', section_title='Overview' -- the one
// canonical row per variety. Non-Overview 'grape' rows are sub-topics of a
// variety (e.g. "Grenache -- New World"), not separate grapes.
// Content shape: "{eyebrow}\n\n{name}\n\n{lede}\n\n{factsBlock}", with the
// country as the second "/"-separated part of the eyebrow.

function grapeHref(chunk) {
  const topic = topicFor(chunk);
  return topic ? `topic-${topic.slug}.html` : `${chunk.source_doc}.html`;
}

// --- A-Z filter (grapes.html, regions.html) -------------------------------
// First letter for filtering, ignoring accents ("Émilie" files under E);
// anything that isn't a letter files under "#".
function initialOf(name) {
  const c = name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().charAt(0).toUpperCase();
  return /[A-Z]/.test(c) ? c : '#';
}

function renderAlphaFilter(initials, lang) {
  const present = new Set(initials);
  const letters = [...'ABCDEFGHIJKLMNOPQRSTUVWXYZ', ...(present.has('#') ? ['#'] : [])];
  const all = lang === 'fr' ? 'Tous' : 'All';
  const label = lang === 'fr' ? 'Filtrer par lettre' : 'Filter by letter';
  const buttons = letters
    .map((l) => `        <button type="button" class="chip" data-letter="${l}" aria-pressed="false"${present.has(l) ? '' : ' disabled'}>${l}</button>`)
    .join('\n');
  return `      <div class="chip-row alpha-filter" role="group" aria-label="${label}">
        <button type="button" class="chip" data-letter="" aria-pressed="true">${all}</button>
${buttons}
      </div>`;
}

// Wires the letter buttons: onLetter(letter) re-filters the page ('' = all).
const ALPHA_FILTER_SCRIPT = `
    function wireAlphaFilter(onLetter) {
      const buttons = [...document.querySelectorAll('.alpha-filter .chip')];
      for (const b of buttons) {
        b.addEventListener('click', () => {
          for (const x of buttons) x.setAttribute('aria-pressed', String(x === b));
          onLetter(b.dataset.letter);
        });
      }
    }`;

async function buildGrapes(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.eq('chunk_type', 'grape').eq('section_title', 'Overview'), lang);
  const grapes = rows
    .map((row) => {
      const [eyebrow = '', name = ''] = row.content.split('\n\n');
      const grapeName = (name || row.source_doc.replace(/^grape-/, '')).trim();
      // The modal's title comes from section_title, which is literally
      // "Overview" on every one of these rows -- use the grape name instead.
      return { name: grapeName, country: eyebrow.split('/')[1]?.trim() || '', chunk: { ...row, section_title: grapeName } };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  if (grapes.length === 0) throw new Error(`no ${lang} grape Overview rows returned`);

  const tiles = grapes
    .map(
      (g) => `        <a class="tile" data-name="${escapeHtml(g.name.toLowerCase())}" data-letter="${initialOf(g.name)}" ${linkAttrs(grapeHref(g.chunk))}>
          <span class="name">${escapeHtml(g.name)}</span>
          <span class="n">${escapeHtml(g.country)}</span>
        </a>`
    )
    .join('\n');

  const t = isFr
    ? {
        home: 'Accueil',
        crumb: 'Cépages',
        title: 'Tous Les Cépages',
        placeholder: 'rechercher un cépage',
        count: (n) => `${n} cépages`,
        noMatch: 'Aucun cépage ne correspond à cette recherche.',
      }
    : {
        home: 'Home',
        crumb: 'Grapes',
        title: 'All Grape Varieties',
        placeholder: 'search grapes',
        count: (n) => `${n} grapes`,
        noMatch: 'No grapes match that search.',
      };

  return renderPage({
    file: 'grapes.html',
    lang,
    title: isFr ? 'Cépages — Thirsty Cunt' : 'Grapes — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Chaque cépage de la base de connaissances, consultable par nom.'
      : 'Every grape variety in the knowledge base, browsable by name.',
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${t.home}</a> / ${t.crumb}</p>
      <h1 class="page-title">${t.title}</h1>

      <input class="search-input" type="search" id="grapeSearch" placeholder="${t.placeholder}" aria-label="${t.placeholder}" style="margin-bottom: 20px" />
${renderAlphaFilter(grapes.map((g) => initialOf(g.name)), lang)}

      <p class="count" id="grapeCount">${t.count(grapes.length)}</p>
      <div id="grapesGrid" class="grid tiles">
${tiles}
      </div>
    </div>
  </main>`,
    // Filters the pre-rendered tiles in place, by search text and letter.
    script: `
  <script>
    (() => {${ALPHA_FILTER_SCRIPT}
      const input = document.getElementById('grapeSearch');
      const count = document.getElementById('grapeCount');
      const tiles = [...document.querySelectorAll('#grapesGrid .tile')];
      let letter = '';
      function apply() {
        const q = input.value.trim().toLowerCase();
        let shown = 0;
        for (const tile of tiles) {
          tile.hidden = (Boolean(q) && !tile.dataset.name.includes(q)) || (Boolean(letter) && tile.dataset.letter !== letter);
          if (!tile.hidden) shown++;
        }
        const noun = ${isFr ? "'cépage'" : "'grape'"};
        count.textContent = shown === 0 ? '${t.noMatch}' : \`\${shown} \${noun}\${shown !== 1 ? 's' : ''}\`;
      }
      input.addEventListener('input', apply);
      wireAlphaFilter((l) => { letter = l; apply(); });
    })();
  </script>`,
  });
}

// --- regions.html -----------------------------------------------------------
// chunk_type='region' isn't one row per browsable region -- it's ~35
// macro-region "chapters" (source_doc, e.g. "region-italy-central"), each
// holding section rows for its sub-regions (Chianti, Tuscany, ...). There's
// no per-country label stored anywhere, so group names come from the slug
// (REGION_GROUP_NAMES_FR above, for French).

async function buildRegions(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.eq('chunk_type', 'region'), lang);
  const groups = groupBySourceDoc(rows)
    .map(([sourceDoc, groupRows]) => {
      const stripped = sourceDoc.replace(/^region-/, '');
      return {
        name: isFr ? groupNameFr(stripped) : humanizeSlug(stripped),
        rows: groupRows.map((row) => {
          const topic = topicFor(row);
          const href =
            row.section_title === 'Overview' && topic
              ? `topic-${topic.slug}.html`
              : sectionPageHref(row);
          return { ...row, title: rowTitle(row), href };
        }),
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  if (groups.length === 0) throw new Error(`no ${lang} region rows returned`);

  const untitled = isFr ? 'Sans titre' : 'Untitled';

  // <details> keeps every sub-region in the HTML (crawlable) while still
  // collapsing each group, with no JavaScript needed.
  const sections = groups
    .map((group) => {
      const items = group.rows
        .map(
          (chunk) => `          <a class="row-item" ${linkAttrs(chunk.href)}>
            <span class="t">${escapeHtml(chunk.title || untitled)}</span>
            ${kindLabel(chunk.chunk_type, lang) ? `<span class="k">${escapeHtml(kindLabel(chunk.chunk_type, lang))}</span>` : ''}
          </a>`
        )
        .join('\n');
      return `        <details class="region-group" data-letter="${initialOf(group.name)}">
          <summary class="list-head"><span>${escapeHtml(group.name)}</span><span>${group.rows.length}</span></summary>
${items}
        </details>`;
    })
    .join('\n');

  return renderPage({
    file: 'regions.html',
    lang,
    title: isFr ? 'Régions — Thirsty Cunt' : 'Regions — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Toutes les régions viticoles dont nous avons parlé, regroupées et consultables.'
      : "Every wine region we've written about, grouped and browsable.",
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${isFr ? 'Accueil' : 'Home'}</a> / ${isFr ? 'Régions' : 'Regions'}</p>
      <h1 class="page-title">${isFr ? 'Régions Viticoles' : 'Wine Regions'}</h1>

${renderAlphaFilter(groups.map((g) => initialOf(g.name)), lang)}
      <div id="regionGroups">
${sections}
      </div>
    </div>
  </main>`,
    // Shows only the region groups starting with the chosen letter.
    script: `
  <script>
    (() => {${ALPHA_FILTER_SCRIPT}
      const groups = [...document.querySelectorAll('#regionGroups .region-group')];
      wireAlphaFilter((letter) => {
        for (const g of groups) g.hidden = Boolean(letter) && g.dataset.letter !== letter;
      });
    })();
  </script>`,
  });
}

// --- guides.html ------------------------------------------------------------
// guide/comparison chunks come in 2-3 rows per source_doc ("Concept" +
// "Teaching", "Overview" + "Practice", ...). One card per source_doc, opening
// its first row in the modal -- 7 groups, not enough for detail pages.
// Titles come from source_doc (GUIDE_TITLES_FR above, for French):
// section_title suffixes are inconsistent. enology rows are excluded: they
// already have their own topic pages.

// Each guide/comparison has its own page named after its source_doc
// (guide-how-to-taste-wine.html), in the same directory as guides.html.
// Mirrored by chunkHref() in supabase-client.js.
function guidePagePath(sourceDoc) {
  return `${sourceDoc}.html`;
}

// A part's content opens with its heading ("Wine Tasting Framework —
// Overview"), then the body after a blank line.
function splitPart(content) {
  const [heading, ...rest] = content.split('\n\n');
  return { heading: heading.trim(), body: rest.join('\n\n') };
}

function guidePreview(group) {
  const body = stripMarkdown(splitPart(group.rows[0].content).body);
  return body.length > 160 ? `${body.slice(0, 160)}…` : body;
}

async function fetchGuideGroups(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.in('chunk_type', ['guide', 'comparison']), lang);
  const groups = groupBySourceDoc(rows).map(([sourceDoc, groupRows]) => {
    const stripped = sourceDoc.replace(/^(guide|comparison)-/, '');
    return { sourceDoc, title: isFr ? guideTitleFr(stripped) : humanizeSlug(stripped), rows: groupRows };
  });
  if (groups.length === 0) throw new Error(`no ${lang} guide/comparison rows returned`);
  return { rows, groups };
}

function guidePartWord(n, lang) {
  return lang === 'fr' ? `${n} partie${n !== 1 ? 's' : ''}` : `${n} part${n !== 1 ? 's' : ''}`;
}

async function buildGuides(lang) {
  const isFr = lang === 'fr';
  const { groups } = await fetchGuideGroups(lang);

  const readMore = isFr ? 'Lire' : 'Read';
  const card = (group) => `        <a class="card topic" href="${guidePagePath(group.sourceDoc)}">
          <span class="card-meta">${guidePartWord(group.rows.length, lang)}</span>
          <span class="card-title sm">${escapeHtml(group.title)}</span>
          <p>${escapeHtml(guidePreview(group))}</p>
          <span class="more">${readMore} &rarr;</span>
        </a>`;

  // Guides teach how wine works; comparisons set two things side by side.
  const sections = [
    ['guide', isFr ? 'Guides' : 'Guides'],
    ['comparison', isFr ? 'Comparaisons' : 'Comparisons'],
  ]
    .map(([kind, heading]) => {
      const kindGroups = groups.filter((g) => g.rows[0].chunk_type === kind);
      if (kindGroups.length === 0) return '';
      return `      <section style="margin-top: 48px">
        <p class="list-head">${heading}</p>
        <div class="grid answers-3" style="margin-top: 24px">
${kindGroups.map(card).join('\n')}
        </div>
      </section>`;
    })
    .filter(Boolean)
    .join('\n');

  return renderPage({
    file: 'guides.html',
    lang,
    title: isFr ? 'Guides — Thirsty Cunt' : 'Guides — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Comment fonctionne le vin, et comment les bouteilles se comparent, en format plus long qu’une simple réponse.'
      : 'How wine works, and how bottles compare, in longer form than a single answer.',
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${isFr ? 'Accueil' : 'Home'}</a> / ${isFr ? 'Guides' : 'Guides'}</p>
      <h1 class="page-title">${isFr ? 'Guides Et Comparaisons' : 'Guides &amp; Comparisons'}</h1>
      <p class="lede sm">${
        isFr
          ? 'Des lectures plus longues qu’une simple réponse : des guides en plusieurs parties sur le fonctionnement du vin, et des comparaisons côte à côte. Une petite sélection, choisie avec soin.'
          : 'Longer reads than a single answer: multi-part guides on how wine works, and side-by-side comparisons. A small, handpicked set.'
      }</p>

${sections}
    </div>
  </main>`,
  });
}

// --- guide-*.html / comparison-*.html -----------------------------------------
