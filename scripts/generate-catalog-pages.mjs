// A few guide bodies (e.g. "How To Taste Wine") are written as a numbered
// Markdown list with **bold** step names -- fine in the full guide, but
// the card preview here just wants a plain-text snippet, not raw
// "1. **Look** — ..." syntax.
function stripMarkdown(text) {
  return text
    .replace(/^\s*(?:\d+\.|-)\s+/gm, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\s*\n\s*/g, '; ')
    .trim();
}

function groupNameFr(strippedSlug) {
  return REGION_GROUP_NAMES_FR[strippedSlug] ?? humanizeSlug(strippedSlug);
}

function guideTitleFr(strippedSlug) {
  return GUIDE_TITLES_FR[strippedSlug] ?? humanizeSlug(strippedSlug);
}

// Where a grape/region row lives (mirrored by chunkHref() in
// supabase-client.js). hrefs are plain same-directory filenames: English
// and French catalog pages each sit next to their own language's pages.
//   - a source_doc with a topic page: that topic page (grape Overview rows,
//     and the Overview row of the six region topics)
//   - any other grape: its own grape-*.html page
//   - a region section: its region-*.html page, at that section's anchor
function topicFor(chunk) {
  return TOPICS.find((t) => t.kind === chunk.chunk_type && t.sourceDoc === chunk.source_doc);
}

function regionPartAnchor(index) {
  return `part-${index + 1}`;
}

function linkAttrs(href) {
  return `href="${href}"`;
}

function hreflangAlternates(file) {
  return [
    { hreflang: 'en', href: `${BASE_URL}/${file}` },
    { hreflang: 'fr', href: `${BASE_URL}/fr/${file}` },
    { hreflang: 'x-default', href: `${BASE_URL}/${file}` },
  ];
}

// nav is the header item to highlight; defaults to the page itself.
function renderPage({ file, nav = file, title, description, main, script = '', lang, jsonLd = [] }) {
  const ap = assetPrefixFor(lang);
  const isFr = lang === 'fr';
  return [
    renderHead({ title, description, lang, assetPrefix: ap, alternates: hreflangAlternates(file), jsonLd }),
    GENERATED_MARKER,
    renderHeader({
      currentNav: nav,
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${file}`,
      enHref: isFr ? `../${file}` : null,
    }),
    main,
    renderFooter({
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${file}`,
      enHref: isFr ? `../${file}` : null,
    }),
    '',
    `  <script src="${ap}supabase-client.js"></script>${script}
</body>
</html>
`,
  ].join('\n');
}

// --- grapes.html ------------------------------------------------------------
// Grapes means chunk_type='grape', section_title='Overview' -- the one
// canonical row per variety. Non-Overview 'grape' rows are sub-topics of a
// variety (e.g. "Grenache -- New World"), not separate grapes.
// Content shape: "{eyebrow}\n\n{name}\n\n{lede}\n\n{factsBlock}", with the
// country as the second "/"-separated part of the eyebrow.

function grapeHref(chunk) {
  const topic = topicFor(chunk);
  return topic ? `topic-${topic.slug}.html` : `${chunk.source_doc}.html`;
}

async function buildGrapes(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.eq('chunk_type', 'grape').eq('section_title', 'Overview'), lang);
  const grapes = rows
    .map((row) => {
      const [eyebrow = '', name = ''] = row.content.split('\n\n');
      const grapeName = (name || row.source_doc.replace(/^grape-/, '')).trim();
      // The modal's title comes from section_title, which is literally
      // "Overview" on every one of these rows -- use the grape name instead.
      return { name: grapeName, country: eyebrow.split('/')[1]?.trim() || '', chunk: { ...row, section_title: grapeName } };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  if (grapes.length === 0) throw new Error(`no ${lang} grape Overview rows returned`);

  const tiles = grapes
    .map(
      (g) => `        <a class="tile" data-name="${escapeHtml(g.name.toLowerCase())}" ${linkAttrs(grapeHref(g.chunk))}>
          <span class="name">${escapeHtml(g.name)}</span>
          <span class="n">${escapeHtml(g.country)}</span>
        </a>`
    )
    .join('\n');

  const t = isFr
    ? {
        home: 'Accueil',
        crumb: 'Cépages',
        title: 'Tous Les Cépages',
        lede: (n) => `${n} cépages. Cliquez sur l'un d'eux pour voir ce que nous en avons écrit.`,
        placeholder: 'rechercher un cépage',
        count: (n) => `${n} cépages`,
        noMatch: 'Aucun cépage ne correspond à cette recherche.',
      }
    : {
        home: 'Home',
        crumb: 'Grapes',
        title: 'All Grape Varieties',
        lede: (n) => `${n} varieties. Click one to see what we've written about it.`,
        placeholder: 'search grapes',
        count: (n) => `${n} grapes`,
        noMatch: 'No grapes match that search.',
      };

  return renderPage({
    file: 'grapes.html',
    lang,
    title: isFr ? 'Cépages — Thirsty Cunt' : 'Grapes — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Chaque cépage de la base de connaissances, consultable par nom.'
      : 'Every grape variety in the knowledge base, browsable by name.',
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${t.home}</a> / ${t.crumb}</p>
      <h1 class="page-title">${t.title}</h1>
      <p class="lede sm">${t.lede(grapes.length)}</p>

      <input class="search-input" type="search" id="grapeSearch" placeholder="${t.placeholder}" aria-label="${t.placeholder}" style="margin-bottom: 28px" />

      <p class="count" id="grapeCount">${t.count(grapes.length)}</p>
      <div id="grapesGrid" class="grid tiles">
${tiles}
      </div>
    </div>
  </main>`,
    // Filters the pre-rendered tiles in place.
    script: `
  <script>
    (() => {
      const input = document.getElementById('grapeSearch');
      const count = document.getElementById('grapeCount');
      const tiles = [...document.querySelectorAll('#grapesGrid .tile')];
      input.addEventListener('input', () => {
        const q = input.value.trim().toLowerCase();
        let shown = 0;
        for (const tile of tiles) {
          tile.hidden = Boolean(q) && !tile.dataset.name.includes(q);
          if (!tile.hidden) shown++;
        }
        const noun = ${isFr ? "'cépage'" : "'grape'"};
        count.textContent = shown === 0 ? '${t.noMatch}' : \`\${shown} \${noun}\${shown !== 1 ? 's' : ''}\`;
      });
    })();
  </script>`,
  });
}

// --- regions.html -----------------------------------------------------------
// chunk_type='region' isn't one row per browsable region -- it's ~35
// macro-region "chapters" (source_doc, e.g. "region-italy-central"), each
// holding section rows for its sub-regions (Chianti, Tuscany, ...). There's
// no per-country label stored anywhere, so group names come from the slug
// (REGION_GROUP_NAMES_FR above, for French).

async function buildRegions(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.eq('chunk_type', 'region'), lang);
  const groups = groupBySourceDoc(rows)
    .map(([sourceDoc, groupRows]) => {
      const stripped = sourceDoc.replace(/^region-/, '');
      const sectionRows = groupRows.filter((row) => row.section_title !== 'Overview');
      return {
        name: isFr ? groupNameFr(stripped) : humanizeSlug(stripped),
        rows: groupRows.map((row) => {
          const topic = topicFor(row);
          const href =
            row.section_title === 'Overview' && topic
              ? `topic-${topic.slug}.html`
              : `${sourceDoc}.html#${regionPartAnchor(sectionRows.indexOf(row))}`;
          return { ...row, title: rowTitle(row), href };
        }),
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  if (groups.length === 0) throw new Error(`no ${lang} region rows returned`);

  const untitled = isFr ? 'Sans titre' : 'Untitled';

  // <details> keeps every sub-region in the HTML (crawlable) while still
  // collapsing each group, with no JavaScript needed.
  const sections = groups
    .map((group) => {
      const items = group.rows
        .map(
          (chunk) => `          <a class="row-item" ${linkAttrs(chunk.href)}>
            <span class="id">${escapeHtml(chunk.source_doc.toUpperCase())}</span>
            <span class="t">${escapeHtml(chunk.title || untitled)}</span>
            <span class="k">${escapeHtml(chunk.chunk_type.toUpperCase())}</span>
          </a>`
        )
        .join('\n');
      return `        <details class="region-group">
          <summary class="list-head"><span>${escapeHtml(group.name)}</span><span>${group.rows.length}</span></summary>
${items}
        </details>`;
    })
    .join('\n');

  return renderPage({
    file: 'regions.html',
    lang,
    title: isFr ? 'Régions — Thirsty Cunt' : 'Regions — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Toutes les régions viticoles dont nous avons parlé, regroupées et consultables.'
      : "Every wine region we've written about, grouped and browsable.",
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${isFr ? 'Accueil' : 'Home'}</a> / ${isFr ? 'Régions' : 'Regions'}</p>
      <h1 class="page-title">${isFr ? 'Régions Viticoles' : 'Wine Regions'}</h1>
      <p class="lede sm">${
        isFr
          ? `${groups.length} régions, ${rows.length} sous-thèmes au total. Développez-en une pour explorer.`
          : `${groups.length} regions, ${rows.length} sub-topics between them. Expand one to browse.`
      }</p>

      <div>
${sections}
      </div>
    </div>
  </main>`,
  });
}

// --- guides.html ------------------------------------------------------------
// guide/comparison chunks come in 2-3 rows per source_doc ("Concept" +
// "Teaching", "Overview" + "Practice", ...). One card per source_doc, opening
// its first row in the modal -- 7 groups, not enough for detail pages.
// Titles come from source_doc (GUIDE_TITLES_FR above, for French):
// section_title suffixes are inconsistent. enology rows are excluded: they
// already have their own topic pages.

// Each guide/comparison has its own page named after its source_doc
// (guide-how-to-taste-wine.html), in the same directory as guides.html.
// Mirrored by chunkHref() in supabase-client.js.
function guidePagePath(sourceDoc) {
  return `${sourceDoc}.html`;
}

// A part's content opens with its heading ("Wine Tasting Framework —
// Overview"), then the body after a blank line.
function splitPart(content) {
  const [heading, ...rest] = content.split('\n\n');
  return { heading: heading.trim(), body: rest.join('\n\n') };
}

function guidePreview(group) {
  const body = stripMarkdown(splitPart(group.rows[0].content).body);
  return body.length > 160 ? `${body.slice(0, 160)}…` : body;
}

async function fetchGuideGroups(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.in('chunk_type', ['guide', 'comparison']), lang);
  const groups = groupBySourceDoc(rows).map(([sourceDoc, groupRows]) => {
    const stripped = sourceDoc.replace(/^(guide|comparison)-/, '');
    return { sourceDoc, title: isFr ? guideTitleFr(stripped) : humanizeSlug(stripped), rows: groupRows };
  });
  if (groups.length === 0) throw new Error(`no ${lang} guide/comparison rows returned`);
  return { rows, groups };
}

function guidePartWord(n, lang) {
  return lang === 'fr' ? `${n} partie${n !== 1 ? 's' : ''}` : `${n} part${n !== 1 ? 's' : ''}`;
}

async function buildGuides(lang) {
  const isFr = lang === 'fr';
  const { rows, groups } = await fetchGuideGroups(lang);

  const readMore = isFr ? 'Lire' : 'Read';

  const cards = groups
    .map((group) => {
      const primary = group.rows[0];
      return `        <a class="card topic" href="${guidePagePath(group.sourceDoc)}">
          <span class="card-meta">${escapeHtml(primary.chunk_type.toUpperCase())} &middot; ${guidePartWord(group.rows.length, lang)}</span>
          <span class="card-title sm">${escapeHtml(group.title)}</span>
          <p>${escapeHtml(guidePreview(group))}</p>
          <span class="more">${readMore} &rarr;</span>
        </a>`;
    })
    .join('\n');

  return renderPage({
    file: 'guides.html',
    lang,
    title: isFr ? 'Guides — Thirsty Cunt' : 'Guides — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Comment fonctionne le vin, et comment les bouteilles se comparent, en format plus long qu’une simple réponse.'
      : 'How wine works, and how bottles compare, in longer form than a single answer.',
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${isFr ? 'Accueil' : 'Home'}</a> / ${isFr ? 'Guides' : 'Guides'}</p>
      <h1 class="page-title">${isFr ? 'Guides Et Comparaisons' : 'Guides &amp; Comparisons'}</h1>
      <p class="lede sm">${
        isFr
          ? `${groups.length} guides et comparaisons, ${rows.length} parties au total.`
          : `${groups.length} guides and comparisons, ${rows.length} parts in total.`
      }</p>

      <div class="grid answers-3">
${cards}
      </div>
    </div>
  </main>`,
  });
}

// --- guide-*.html / comparison-*.html -----------------------------------------
// One page per guide/comparison with every part in order (the catalog card
// used to open only the first part in a modal).

async function buildGuidePages(lang) {
  const isFr = lang === 'fr';
  const { groups } = await fetchGuideGroups(lang);
  const ap = assetPrefixFor(lang);
  const t = {
    home: isFr ? 'Accueil' : 'Home',
    guides: isFr ? 'Guides' : 'Guides',
    kind: { guide: isFr ? 'Guide' : 'Guide', comparison: isFr ? 'Comparaison' : 'Comparison' },
    back: isFr ? 'Tous les guides' : 'All guides',
  };

  return groups.map((group) => {
    const file = guidePagePath(group.sourceDoc);
    const kind = group.rows[0].chunk_type;
    const description = guidePreview(group);
    const parts = group.rows
      .map((row) => {
        const { heading, body } = splitPart(row.content);
        return `      <section class="guide-part">
        <h2 class="guide-part-title">${escapeHtml(heading)}</h2>
        <div class="body-copy">
${renderMarkdown(body)}
        </div>
      </section>`;
      })
      .join('\n');

    const html = renderPage({
      file,
      nav: 'guides.html',
      lang,
      title: isFr ? `${group.title} — Thirsty Cunt` : `${group.title} — Thirsty Cunt Knowledge Base`,
      description: escapeHtml(description),
      jsonLd: [articleSchema({ headline: group.title, description, url: `${isFr ? 'fr/' : ''}${file}`, lang })],
      main: `  <main class="has-hero">
${renderHeroBand({
  breadcrumb: `<a href="${ap}index.html">${t.home}</a> / <a href="guides.html">${t.guides}</a> / ${escapeHtml(group.title)}`,
  eyebrow: `${t.kind[kind] ?? kind} · ${guidePartWord(group.rows.length, lang)}`,
  title: group.title,
  lede: description,
})}
    <div class="wrap">
${parts}
      <p class="guide-back"><a href="guides.html">&larr; ${t.back}</a></p>
    </div>
  </main>`,
    });
    return [file, html];
  });
}

// --- grape-*.html --------------------------------------------------------------
// One page per grape without a topic page: overview, facts, any extra
// sections, and every answer that mentions the grape by name.

async function fetchAnswerRows(lang) {
  const rows = await fetchLangRows((q) => q.in('chunk_type', ['qa', 'region-qa']), lang);
  const dir = lang === 'fr' ? 'fr/' : '';
  return rows.filter((row) => {
    const path = `${dir}${answerPagePath(row.source_doc)}`;
    return !(path in REDIRECTS) && existsSync(path);
  });
}

function renderAnswerRows(rows) {
  return rows
    .map(
      (row) => `        <a class="row-item" href="${answerPagePath(row.source_doc)}">
          <span class="id">${escapeHtml(row.source_doc.toUpperCase())}</span>
          <span class="t">${escapeHtml(deriveQuestion(row.content))}</span>
          <span class="k">${escapeHtml(row.chunk_type.toUpperCase())}</span>
        </a>`
    )
    .join('\n');
}

function renderSections(parts) {
  return parts
    .map(
      ({ id, heading, body }) => `      <section class="guide-part"${id ? ` id="${id}"` : ''}>
        <h2 class="guide-part-title">${escapeHtml(heading)}</h2>
        <div class="body-copy">
${renderMarkdown(body)}
        </div>
      </section>`
    )
    .join('\n');
}

// Grape names like "Riesling (Australia)" are regional takes on a grape.
// Their answer list only includes answers that mention the place too;
// style qualifiers ("Old-Vine", "White") don't narrow the match.
const STYLE_QUALIFIERS = new Set(['White', 'Nebbiolo', 'Old-Vine', 'Higher Quality', 'Rot']);
const PLACE_PATTERNS = {
  NZ: 'New Zealand|NZ',
  USA: 'USA|America|\\bUS\\b',
  Italy: 'Ital',
  Argentina: 'Argentin',
  'Argentine High-Altitude': 'Argentin',
  Lebanon: 'Leban',
  Uruguay: 'Urugua',
  Israel: 'Israel',
  'Southern Rhône': 'Rhône',
  'Northern Rhône': 'Rhône',
};

function grapeAnswerMatcher(name) {
  const [, base, qualifier] = name.match(/^(.*?)\s*(?:\((.*)\))?\s*$/);
  const mentionsBase = new RegExp(`(^|[^\\p{L}])${escapeRegex(base)}(?![\\p{L}])`, 'u');
  const place = qualifier && !STYLE_QUALIFIERS.has(qualifier) ? PLACE_PATTERNS[qualifier] ?? escapeRegex(qualifier) : null;
  const mentionsPlace = place ? new RegExp(place, 'u') : null;
  return {
    base,
    matches: (content) => mentionsBase.test(content) && (!mentionsPlace || mentionsPlace.test(content)),
  };
}

async function buildGrapePages(lang) {
  const isFr = lang === 'fr';
  const ap = assetPrefixFor(lang);
  const [grapeRows, answerRows] = await Promise.all([
    fetchRows((q) => q.eq('chunk_type', 'grape'), lang),
    fetchAnswerRows(lang),
  ]);
  const pages = [];
  for (const [sourceDoc, rows] of groupBySourceDoc(grapeRows)) {
    const overviewRow = rows.find((row) => row.section_title === 'Overview');
    // grape-varieties is a reference list, not a grape; topic grapes
    // already have their own page.
    if (!overviewRow || topicFor(overviewRow)) continue;

    const overview = parseOverview(overviewRow.content);
    const name = overview.name || humanizeSlug(sourceDoc.replace(/^grape-/, ''));
    const matcher = grapeAnswerMatcher(name);
    const matchName = matcher.base;
    const answers = answerRows.filter((row) => matcher.matches(row.content)).slice(0, 60);
    // Regional takes on a topic grape ("Riesling (Australia)") also point to
    // that grape's topic page.
    const baseTopic = TOPICS.find((t) => t.kind === 'grape' && t.topicName === matchName);
    const baseTopicLink = baseTopic
      ? `      <p class="guide-back" style="margin-bottom: 40px"><a href="topic-${baseTopic.slug}.html">${
          isFr ? `Tout sur ${escapeHtml(matchName)}` : `Everything on ${escapeHtml(matchName)}`
        } &rarr;</a></p>\n`
      : '';
    const sections = rows.filter((row) => row !== overviewRow).map((row) => splitHeading(row));

    const file = `${sourceDoc}.html`;
    const description = shorten(overview.lede || name);
    const facts = overview.facts
      .map(([key, value]) => `          <div><dt>${escapeHtml(key)}</dt><dd>${escapeHtml(value)}</dd></div>`)
      .join('\n');
    const countLine = isFr
      ? `${answers.length} réponse${answers.length !== 1 ? 's' : ''} mentionnant ${matchName}`
      : `${answers.length} Answer${answers.length !== 1 ? 's' : ''} Mentioning ${matchName}`;

    const html = renderPage({
      file,
      nav: 'grapes.html',
      lang,
      title: isFr ? `${name} — Thirsty Cunt` : `${name} — Thirsty Cunt Knowledge Base`,
      description: escapeHtml(description),
      jsonLd: [topicSchema({ name, description, url: `${isFr ? 'fr/' : ''}${file}`, kind: 'grape', lang })],
      main: `  <main class="has-hero">
${renderHeroBand({
  breadcrumb: `<a href="${ap}index.html">${isFr ? 'Accueil' : 'Home'}</a> / <a href="grapes.html">${isFr ? 'Cépages' : 'Grapes'}</a> / ${escapeHtml(name)}`,
  eyebrow: overview.eyebrow,
  title: name,
  lede: overview.lede,
  aside: facts ? `        <dl class="facts">\n${facts}\n        </dl>` : '',
})}
    <div class="wrap">
${baseTopicLink}${renderSections(sections)}
${answers.length ? `      <p class="list-head">${escapeHtml(countLine)}</p>
      <div style="margin-bottom: 56px">
${renderAnswerRows(answers)}
      </div>` : ''}
      <p class="guide-back"><a href="grapes.html">&larr; ${isFr ? 'Tous les cépages' : 'All grapes'}</a></p>
    </div>
  </main>`,
    });
    pages.push([file, html]);
  }
  if (pages.length === 0) throw new Error(`no ${lang} grape pages built`);
  return pages;
}

// --- region-*.html -------------------------------------------------------------
// One page per region chapter that has sections (the six region topics'
// Overview rows stay on their topic pages). Sections get part-N anchors,
// which regions.html links to.

async function buildRegionPages(lang) {
  const isFr = lang === 'fr';
  const ap = assetPrefixFor(lang);
  const rows = await fetchRows((q) => q.eq('chunk_type', 'region'), lang);
  const pages = [];
  for (const [sourceDoc, groupRows] of groupBySourceDoc(rows)) {
    const sectionRows = groupRows.filter((row) => row.section_title !== 'Overview');
    if (sectionRows.length === 0) continue;

    const stripped = sourceDoc.replace(/^region-/, '');
    const name = isFr ? groupNameFr(stripped) : humanizeSlug(stripped);
    const parts = sectionRows.map((row, i) => ({ id: regionPartAnchor(i), ...splitHeading(row) }));
    const topic = TOPICS.find((t) => t.kind === 'region' && t.sourceDoc === sourceDoc);
    const file = `${sourceDoc}.html`;
    const description = shorten(stripMarkdown(parts[0].body) || name);
    const sectionWord = isFr
      ? `${parts.length} section${parts.length !== 1 ? 's' : ''}`
      : `${parts.length} section${parts.length !== 1 ? 's' : ''}`;
    const toc = parts
      .map(({ id, heading }) => `        <li><a href="#${id}">${escapeHtml(heading)}</a></li>`)
      .join('\n');
    const topicLink = topic
      ? `      <p class="guide-back" style="margin-bottom: 40px"><a href="topic-${topic.slug}.html">${
          isFr ? 'Toutes nos réponses sur cette région' : 'All our answers on this region'
        } &rarr;</a></p>\n`
      : '';

    const html = renderPage({
      file,
      nav: 'regions.html',
      lang,
      title: isFr ? `${name} — Thirsty Cunt` : `${name} — Thirsty Cunt Knowledge Base`,
      description: escapeHtml(description),
      jsonLd: [topicSchema({ name, description, url: `${isFr ? 'fr/' : ''}${file}`, kind: 'region', lang })],
      main: `  <main class="has-hero">
${renderHeroBand({
  breadcrumb: `<a href="${ap}index.html">${isFr ? 'Accueil' : 'Home'}</a> / <a href="regions.html">${isFr ? 'Régions' : 'Regions'}</a> / ${escapeHtml(name)}`,
  eyebrow: `${isFr ? 'Région viticole' : 'Wine Region'} · ${sectionWord}`,
  title: name,
  lede: description,
})}
    <div class="wrap">
${topicLink}      <ol class="toc">
${toc}
      </ol>
${renderSections(parts)}
      <p class="guide-back"><a href="regions.html">&larr; ${isFr ? 'Toutes les régions' : 'All regions'}</a></p>
    </div>
  </main>`,
    });
    pages.push([file, html]);
  }
  if (pages.length === 0) throw new Error(`no ${lang} region pages built`);
  return pages;
}

// Single-page builds return one HTML string; multi-page builds return
// [[file, html], ...].
const builds = [
  ['grapes.html', buildGrapes],
  ['regions.html', buildRegions],
  ['guides.html', buildGuides],
  ['guide pages', buildGuidePages],
  ['grape pages', buildGrapePages],
  ['region pages', buildRegionPages],
];

mkdirSync('fr', { recursive: true });

let failed = 0;
for (const [name, build] of builds) {
  for (const lang of ['en', 'fr']) {
    const dir = lang === 'fr' ? 'fr/' : '';
    try {
      const output = await build(lang);
      const files = typeof output === 'string' ? [[name, output]] : output;
      for (const [file, html] of files) {
        writeFileSync(`${dir}${file}`, html);
        console.log(`  -> ${dir}${file}`);
      }
    } catch (error) {
      console.error(`  !! ${dir}${name}: ${error.message} -- kept the existing file(s)`);
      failed++;
    }
  }
}
if (failed) process.exitCode = 1;
