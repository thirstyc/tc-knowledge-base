function fetchLangRows(applyFilter, lang) {
  return fetchAllRows(() =>
    applyFilter(
      supabase
        .from('knowledge_chunks')
        .select('id, content, source_doc, section_title, chunk_type')
        .eq('status', 'published')
        .eq('lang', lang)
    )
      .order('source_doc')
      .order('id')
  );
}

// Parts within a source_doc are shown in id order (chunk_index is never
// set). French rows were inserted in batches, so their ids don't follow the
// English order -- but their section_title is still the English one, so
// each French row is ordered by the id of its English counterpart instead.
async function fetchRows(applyFilter, lang) {
  const rows = await fetchLangRows(applyFilter, lang);
  if (lang === 'en') return rows;

  const key = (r) => `${r.source_doc}\n${r.section_title}`;
  const englishId = new Map((await fetchLangRows(applyFilter, 'en')).map((r) => [key(r), r.id]));
  const docOrder = new Map();
  for (const r of rows) if (!docOrder.has(r.source_doc)) docOrder.set(r.source_doc, docOrder.size);
  const position = (r) => englishId.get(key(r)) ?? Infinity;
  // Two unmatched rows give Infinity - Infinity = NaN, which falls through
  // to the id tiebreaker.
  return rows.sort(
    (a, b) => docOrder.get(a.source_doc) - docOrder.get(b.source_doc) || position(a) - position(b) || a.id - b.id
  );
}

// Region/grape section rows open with their heading line, then the body.
// section_title is never translated (it's the join key back to English, see
// fetchRows), and in English it sometimes carries a slug suffix ("Quick
// regional summary alsace"), so the heading line is the better title in both
// languages. A few translations dropped that line (the text starts straight
// into the body), so only a short single first line counts as a heading.
function splitHeading(row) {
  const [first, ...rest] = row.content.split('\n');
  const heading = first.trim();
  if (heading && heading.length <= 120) return { heading, body: rest.join('\n').trim() };
  return { heading: row.section_title, body: row.content };
}

function rowTitle(chunk) {
  return splitHeading(chunk).heading;
}

// Overview content is "eyebrow\n\nname\n\nlede\n\nKey: value\nKey: value"
// (same parser as generate-topic-pages.mjs).
function parseOverview(content) {
  const [eyebrow = '', name = '', lede = '', factsBlock = ''] = content.split('\n\n');
  const facts = factsBlock
    .split('\n')
    .map((line) => {
      const sep = line.indexOf(':');
      return sep === -1 ? null : [line.slice(0, sep).trim(), line.slice(sep + 1).trim()];
    })
    .filter(Boolean);
  return { eyebrow: eyebrow.trim(), name: name.trim(), lede: lede.trim(), facts };
}

function shorten(text, max = 160) {
  const flat = text.replace(/\s+/g, ' ').trim();
  return flat.length > max ? `${flat.slice(0, max)}…` : flat;
}

function groupBySourceDoc(rows) {
  const groups = new Map();
  for (const row of rows) {
    if (!groups.has(row.source_doc)) groups.set(row.source_doc, []);
    groups.get(row.source_doc).push(row);
  }
  return [...groups.entries()];
}

function humanizeSlug(slug) {
  return slug
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

