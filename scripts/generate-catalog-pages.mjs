// A few guide bodies (e.g. "How To Taste Wine") are written as a numbered
// Markdown list with **bold** step names -- fine in the full guide, but
// the card preview here just wants a plain-text snippet, not raw
// "1. **Look** — ..." syntax.
function stripMarkdown(text) {
  return text
    .replace(/^\s*(?:\d+\.|-)\s+/gm, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\s*\n\s*/g, '; ')
    .trim();
}

function groupNameFr(strippedSlug) {
  return REGION_GROUP_NAMES_FR[strippedSlug] ?? humanizeSlug(strippedSlug);
}

function guideTitleFr(strippedSlug) {
  return GUIDE_TITLES_FR[strippedSlug] ?? humanizeSlug(strippedSlug);
}

// A grape/region row links to its topic page when one exists (exact
// source_doc match only -- same rule as resolveTopicSlug() in
// supabase-client.js); anything else opens the inline modal. The href is
// always the plain same-directory filename: an English catalog page and its
// French counterpart both sit next to their language's topic pages (root
// and fr/ respectively), so neither needs an assetPrefix here.
function linkAttrs(chunk) {
  const topic = TOPICS.find((t) => t.kind === chunk.chunk_type && t.sourceDoc === chunk.source_doc);
  if (topic) return `href="topic-${topic.slug}.html"`;
  return `href="#" onclick="window.KnowledgeBase.showChunkDetail(${escapeHtml(JSON.stringify(chunk))}); return false;"`;
}

function hreflangAlternates(file) {
  return [
    { hreflang: 'en', href: `${BASE_URL}/${file}` },
    { hreflang: 'fr', href: `${BASE_URL}/fr/${file}` },
    { hreflang: 'x-default', href: `${BASE_URL}/${file}` },
  ];
}

function renderPage({ file, title, description, main, script = '', lang }) {
  const ap = assetPrefixFor(lang);
  const isFr = lang === 'fr';
  return [
    renderHead({ title, description, lang, assetPrefix: ap, alternates: hreflangAlternates(file) }),
    GENERATED_MARKER,
    renderHeader({
      currentNav: file,
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${file}`,
      enHref: isFr ? `../${file}` : null,
    }),
    main,
    renderFooter({
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${file}`,
      enHref: isFr ? `../${file}` : null,
    }),
    '',
    `  <script src="${ap}supabase-client.js"></script>${script}
</body>
</html>
`,
  ].join('\n');
}

// --- grapes.html ------------------------------------------------------------
// Grapes means chunk_type='grape', section_title='Overview' -- the one
// canonical row per variety. Non-Overview 'grape' rows are sub-topics of a
// variety (e.g. "Grenache -- New World"), not separate grapes.
// Content shape: "{eyebrow}\n\n{name}\n\n{lede}\n\n{factsBlock}", with the
// country as the second "/"-separated part of the eyebrow.

async function buildGrapes(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.eq('chunk_type', 'grape').eq('section_title', 'Overview'), lang);
  const grapes = rows
    .map((row) => {
      const [eyebrow = '', name = ''] = row.content.split('\n\n');
      const grapeName = (name || row.source_doc.replace(/^grape-/, '')).trim();
      // The modal's title comes from section_title, which is literally
      // "Overview" on every one of these rows -- use the grape name instead.
      return { name: grapeName, country: eyebrow.split('/')[1]?.trim() || '', chunk: { ...row, section_title: grapeName } };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  if (grapes.length === 0) throw new Error(`no ${lang} grape Overview rows returned`);

  const tiles = grapes
    .map(
      (g) => `        <a class="tile" data-name="${escapeHtml(g.name.toLowerCase())}" ${linkAttrs(g.chunk)}>
          <span class="name">${escapeHtml(g.name)}</span>
          <span class="n">${escapeHtml(g.country)}</span>
        </a>`
    )
    .join('\n');

  const t = isFr
    ? {
        home: 'Accueil',
        crumb: 'Cépages',
        title: 'Tous Les Cépages',
        lede: (n) => `${n} cépages. Cliquez sur l'un d'eux pour voir ce que nous en avons écrit.`,
        placeholder: 'rechercher un cépage',
        count: (n) => `${n} cépages`,
        noMatch: 'Aucun cépage ne correspond à cette recherche.',
      }
    : {
        home: 'Home',
        crumb: 'Grapes',
        title: 'All Grape Varieties',
        lede: (n) => `${n} varieties. Click one to see what we've written about it.`,
        placeholder: 'search grapes',
        count: (n) => `${n} grapes`,
        noMatch: 'No grapes match that search.',
      };

  return renderPage({
    file: 'grapes.html',
    lang,
    title: isFr ? 'Cépages — Thirsty Cunt' : 'Grapes — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Chaque cépage de la base de connaissances, consultable par nom.'
      : 'Every grape variety in the knowledge base, browsable by name.',
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${t.home}</a> / ${t.crumb}</p>
      <h1 class="page-title">${t.title}</h1>
      <p class="lede sm">${t.lede(grapes.length)}</p>

      <input class="search-input" type="search" id="grapeSearch" placeholder="${t.placeholder}" aria-label="${t.placeholder}" style="margin-bottom: 28px" />

      <p class="count" id="grapeCount">${t.count(grapes.length)}</p>
      <div id="grapesGrid" class="grid tiles">
${tiles}
      </div>
    </div>
  </main>`,
    // Filters the pre-rendered tiles in place.
    script: `
  <script>
    (() => {
      const input = document.getElementById('grapeSearch');
      const count = document.getElementById('grapeCount');
      const tiles = [...document.querySelectorAll('#grapesGrid .tile')];
      input.addEventListener('input', () => {
        const q = input.value.trim().toLowerCase();
        let shown = 0;
        for (const tile of tiles) {
          tile.hidden = Boolean(q) && !tile.dataset.name.includes(q);
          if (!tile.hidden) shown++;
        }
        const noun = ${isFr ? "'cépage'" : "'grape'"};
        count.textContent = shown === 0 ? '${t.noMatch}' : \`\${shown} \${noun}\${shown !== 1 ? 's' : ''}\`;
      });
    })();
  </script>`,
  });
}

// --- regions.html -----------------------------------------------------------
// chunk_type='region' isn't one row per browsable region -- it's ~35
// macro-region "chapters" (source_doc, e.g. "region-italy-central"), each
// holding section rows for its sub-regions (Chianti, Tuscany, ...). There's
// no per-country label stored anywhere, so group names come from the slug
// (REGION_GROUP_NAMES_FR above, for French).

async function buildRegions(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.eq('chunk_type', 'region'), lang);
  const groups = groupBySourceDoc(rows)
    .map(([sourceDoc, groupRows]) => {
      const stripped = sourceDoc.replace(/^region-/, '');
      return {
        name: isFr ? groupNameFr(stripped) : humanizeSlug(stripped),
        // The modal's title comes from section_title too, so override it.
        rows: groupRows.map((row) => ({ ...row, section_title: rowTitle(row, lang) })),
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
  if (groups.length === 0) throw new Error(`no ${lang} region rows returned`);

  const untitled = isFr ? 'Sans titre' : 'Untitled';

  // <details> keeps every sub-region in the HTML (crawlable) while still
  // collapsing each group, with no JavaScript needed.
  const sections = groups
    .map((group) => {
      const items = group.rows
        .map(
          (chunk) => `          <a class="row-item" ${linkAttrs(chunk)}>
            <span class="id">${escapeHtml(chunk.source_doc.toUpperCase())}</span>
            <span class="t">${escapeHtml(chunk.section_title || untitled)}</span>
            <span class="k">${escapeHtml(chunk.chunk_type.toUpperCase())}</span>
          </a>`
        )
        .join('\n');
      return `        <details class="region-group">
          <summary class="list-head"><span>${escapeHtml(group.name)}</span><span>${group.rows.length}</span></summary>
${items}
        </details>`;
    })
    .join('\n');

  return renderPage({
    file: 'regions.html',
    lang,
    title: isFr ? 'Régions — Thirsty Cunt' : 'Regions — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Toutes les régions viticoles dont nous avons parlé, regroupées et consultables.'
      : "Every wine region we've written about, grouped and browsable.",
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${isFr ? 'Accueil' : 'Home'}</a> / ${isFr ? 'Régions' : 'Regions'}</p>
      <h1 class="page-title">${isFr ? 'Régions Viticoles' : 'Wine Regions'}</h1>
      <p class="lede sm">${
        isFr
          ? `${groups.length} régions, ${rows.length} sous-thèmes au total. Développez-en une pour explorer.`
          : `${groups.length} regions, ${rows.length} sub-topics between them. Expand one to browse.`
      }</p>

      <div>
${sections}
      </div>
    </div>
  </main>`,
  });
}

// --- guides.html ------------------------------------------------------------
// guide/comparison chunks come in 2-3 rows per source_doc ("Concept" +
// "Teaching", "Overview" + "Practice", ...). One card per source_doc, opening
// its first row in the modal -- 7 groups, not enough for detail pages.
// Titles come from source_doc (GUIDE_TITLES_FR above, for French):
// section_title suffixes are inconsistent. enology rows are excluded: they
// already have their own topic pages.

async function buildGuides(lang) {
  const isFr = lang === 'fr';
  const rows = await fetchRows((q) => q.in('chunk_type', ['guide', 'comparison']), lang);
  const groups = groupBySourceDoc(rows).map(([sourceDoc, groupRows]) => {
    const stripped = sourceDoc.replace(/^(guide|comparison)-/, '');
    return { title: isFr ? guideTitleFr(stripped) : humanizeSlug(stripped), rows: groupRows };
  });
  if (groups.length === 0) throw new Error(`no ${lang} guide/comparison rows returned`);

  const readMore = isFr ? 'Lire' : 'Read';
  const partWord = (n) => (isFr ? `${n} partie${n !== 1 ? 's' : ''}` : `${n} part${n !== 1 ? 's' : ''}`);

  const cards = groups
    .map((group) => {
      const primary = group.rows[0];
      const body = stripMarkdown(primary.content.split('\n\n').slice(1).join(' '));
      const preview = body.length > 160 ? `${body.slice(0, 160)}…` : body;
      const chunk = { ...primary, section_title: group.title };
      return `        <a class="card topic" href="#" onclick="window.KnowledgeBase.showChunkDetail(${escapeHtml(JSON.stringify(chunk))}); return false;">
          <span class="card-meta">${escapeHtml(primary.chunk_type.toUpperCase())} &middot; ${partWord(group.rows.length)}</span>
          <span class="card-title sm">${escapeHtml(group.title)}</span>
          <p>${escapeHtml(preview)}</p>
          <span class="more">${readMore} &rarr;</span>
        </a>`;
    })
    .join('\n');

  return renderPage({
    file: 'guides.html',
    lang,
    title: isFr ? 'Guides — Thirsty Cunt' : 'Guides — Thirsty Cunt Knowledge Base',
    description: isFr
      ? 'Comment fonctionne le vin, et comment les bouteilles se comparent, en format plus long qu’une simple réponse.'
      : 'How wine works, and how bottles compare, in longer form than a single answer.',
    main: `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${assetPrefixFor(lang)}index.html">${isFr ? 'Accueil' : 'Home'}</a> / ${isFr ? 'Guides' : 'Guides'}</p>
      <h1 class="page-title">${isFr ? 'Guides Et Comparaisons' : 'Guides &amp; Comparisons'}</h1>
      <p class="lede sm">${
        isFr
          ? `${groups.length} guides et comparaisons, ${rows.length} parties au total.`
          : `${groups.length} guides and comparisons, ${rows.length} parts in total.`
      }</p>

      <div class="grid answers-3">
${cards}
      </div>
    </div>
  </main>`,
  });
}

const builds = [
  ['grapes.html', buildGrapes],
  ['regions.html', buildRegions],
  ['guides.html', buildGuides],
];

mkdirSync('fr', { recursive: true });

let failed = 0;
for (const [file, build] of builds) {
  for (const lang of ['en', 'fr']) {
    const path = lang === 'fr' ? `fr/${file}` : file;
    try {
      writeFileSync(path, await build(lang));
      console.log(`  -> ${path}`);
    } catch (error) {
      console.error(`  !! ${path}: ${error.message} -- kept the existing file`);
      failed++;
    }
  }
}
if (failed) process.exitCode = 1;
