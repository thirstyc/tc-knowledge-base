// Generates one answer-{slug}.html (and fr/answer-{slug}.html where a French
// file exists) per answer in content/answers/. Run from the repo root:
// node scripts/generate-missing-pages.mjs [--dry-run] [--force]
// (writes into the repo root, same as generate-topic-pages.mjs)
//
// The content lives in this repo, not in Supabase -- see lib/content-files.mjs.
// To change an answer, edit its .md file and re-run this.
//
// Deliberately NOT built from topics.config.mjs's "distinct section_title"
// idea: section_title on qa/region-qa rows is always a difficulty label
// ("Beginner"/"Intermediate"), never a per-answer identifier -- see
// deriveQuestion() in lib/page-shell.mjs and the commit that fixed the
// same misunderstanding in the old browser client. One page per chunk row
// (keyed by its unique, already-readable source_doc) is what actually
// closes the "detail pages" gap flagged in PIPELINE-GAP-AUDIT.md.
//
// French rows share source_doc with their English counterpart (see
// scripts/translate-to-french-deepl.mjs / lib/french-translation-pipeline.mjs),
// so a French row's page lands at fr/answer-{same-slug}.html -- a true
// same-directory sibling of fr/topic-*.html, which
// is why links between generated pages never need an assetPrefix: only
// links to root-only pages (index.html, answers.html, styles.css, ...) do.
//
// Audience pages (curious-drinker/enthusiast/trade) are intentionally not
// generated here: no audience field exists anywhere in the schema, and
// fabricating one would resurrect the exact hand-authored-fake-content
// pattern this generator exists to replace. audience-enthusiast.html stays
// as the one hand-built demo it always was.
//
// Answer pages show no topic or difficulty: the reader-facing page is just
// the question and its answer. The old difficulty-*.html archives are retired
// (see redirects.config.mjs).

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { readAnswerRows, CONTENT_DIR } from '../lib/content-files.mjs';
import {
  renderHeroBand,
  renderHead,
  renderHeader,
  renderFooter,
  deriveQuestion,
  escapeHtml,
  answerPagePath,
  assetPrefixFor,
  frenchSpacing,
} from '../lib/page-shell.mjs';
import { BASE_URL } from '../topics.config.mjs';
import { faqPageSchema } from '../lib/schema-markup-templates.js';
import { REDIRECTS } from '../redirects.config.mjs';
import { renderMarkdown } from '../lib/markdown.mjs';

const DRY_RUN = process.argv.includes('--dry-run');
// Deliberately overwrite a hand-authored file this one time. Not for
// routine use — after a --force run the file carries GENERATED_MARKER and
// every future run overwrites it normally, without needing the flag again.
const FORCE = process.argv.includes('--force');


// Marks a file as safe to regenerate/overwrite on the next run. Hand-authored
// files (like answer-grenache-alcohol-tannin.html) never carry this, so a
// slug collision with one is refused instead of silently clobbering it.
const GENERATED_MARKER = '<!-- Generated by generate-missing-pages.mjs — do not hand-edit -->';

function hreflangAlternates(path) {
  return [
    { hreflang: 'en', href: `${BASE_URL}/${path}` },
    { hreflang: 'fr', href: `${BASE_URL}/fr/${path}` },
    { hreflang: 'x-default', href: `${BASE_URL}/${path}` },
  ];
}

// Longer answers use blank lines between paragraphs and the same small
// Markdown subset as guides (lists, bold); one-line answers render exactly
// as before (a single <p>).
function answerParagraphs(answerBody) {
  return renderMarkdown(answerBody)
    .split('\n')
    .map((line) => `          ${line}`)
    .join('\n');
}

function renderAnswerPage(row, related, lang) {
  const isFr = lang === 'fr';
  const slugPath = answerPagePath(row.source_doc);
  const path = isFr ? `fr/${slugPath}` : slugPath;
  const question = deriveQuestion(row.content);
  const answerBody = row.content.slice(question.length).trim();
  const ap = assetPrefixFor(lang);

  const t = {
    home: isFr ? 'Accueil' : 'Home',
    answers: isFr ? 'Réponses' : 'Answers',
    shortAnswer: isFr ? 'Réponse courte' : 'Short Answer',
    keepGoing: isFr ? 'Continuer' : 'Keep Going',
    readAnswer: isFr ? 'Lire la réponse' : 'Read The Answer',
  };

  const relatedCards = related
    .map((r) => {
      const q = deriveQuestion(r.content);
      const bodyPreview = r.content.slice(q.length).trim().split(/(?<=[.!?])\s+/).slice(0, 1).join(' ');
      return `          <a class="card" href="${answerPagePath(r.source_doc)}">
            <span class="card-title sm">${escapeHtml(q)}</span>
            <p>${escapeHtml(bodyPreview)}</p>
            <span class="more">${t.readAnswer} &rarr;</span>
          </a>`;
    })
    .join('\n');

  return [
    renderHead({
      title: `${escapeHtml(question)} — Thirsty Cunt`,
      description: escapeHtml(answerBody.replace(/\s+/g, ' ').split(/(?<=[.!?])\s+/).slice(0, 2).join(' ')),
      lang,
      assetPrefix: ap,
      alternates: hreflangAlternates(slugPath),
      jsonLd: [faqPageSchema({ url: path, faqs: [{ question, answer: answerBody }], lang })],
    }),
    GENERATED_MARKER,
    renderHeader({
      currentNav: 'answers.html',
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${slugPath}`,
      enHref: isFr ? `../${slugPath}` : null,
    }),
    `  <main class="has-hero">
${renderHeroBand({
  breadcrumb: `<a href="${ap}index.html">${t.home}</a> / <a href="${ap}answers.html">${t.answers}</a> / ${escapeHtml(question)}`,
  title: question,
  variant: 'answer',
})}
    <div class="wrap">
      <article class="sheet">
        <div class="short-answer">
          <p class="k">${t.shortAnswer}</p>
${answerParagraphs(answerBody)}
        </div>
      </article>

      ${related.length > 0 ? `<section style="margin-top: 80px">
        <p class="list-head">${t.keepGoing}</p>
        <div class="grid answers-3" style="margin-top: 28px">
${relatedCards}
        </div>
      </section>` : ''}
    </div>
  </main>`,
    renderFooter({
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${slugPath}`,
      enHref: isFr ? `../${slugPath}` : null,
    }),
    `</body>\n</html>\n`,
  ].join('\n');
}


function isSafeToWrite(path) {
  if (FORCE) return true;
  if (!existsSync(path)) return true;
  return readFileSync(path, 'utf8').includes(GENERATED_MARKER);
}

async function main() {
  // Content comes from content/answers/{en,fr}/*.md, not from Supabase. See
  // lib/content-files.mjs for why, and for how ids are assigned. Editing an
  // answer is editing a file in this repo and re-running this script.
  const fetchedRows = readAnswerRows();
  if (fetchedRows.length === 0) {
    console.error(`No content found in ${CONTENT_DIR}/. Run: node scripts/export-content-files.mjs`);
    process.exitCode = 1;
    return;
  }

  // Rows whose page is listed in redirects.config.mjs are retired: no page,
  // and no links to them from related cards or difficulty archives.
  const pagePathFor = (row) => `${row.lang === 'fr' ? 'fr/' : ''}${answerPagePath(row.source_doc)}`;
  const retired = fetchedRows.filter((row) => pagePathFor(row) in REDIRECTS);
  const allRows = fetchedRows.filter((row) => !(pagePathFor(row) in REDIRECTS));
  if (retired.length) console.log(`Skipped ${retired.length} redirected row(s): ${retired.map(pagePathFor).join(', ')}`);

  mkdirSync('fr', { recursive: true });

  let written = 0;
  let skippedExisting = 0;
  const skippedProtected = [];

  for (const lang of ['en', 'fr']) {
    const rows = allRows.filter((r) => r.lang === lang);

    for (const row of rows) {
      const path = pagePathFor(row);

      if (!isSafeToWrite(path)) {
        skippedProtected.push(path);
        continue;
      }
      if (existsSync(path)) {
        skippedExisting++;
        // Still regenerate — content may have changed since last run.
      }

      // 3 related rows: same chunk_type and language, nearest by id, excluding self.
      const related = rows
        .filter((r) => r.chunk_type === row.chunk_type && r.id !== row.id)
        .sort((a, b) => Math.abs(a.id - row.id) - Math.abs(b.id - row.id))
        .slice(0, 3);

      if (!DRY_RUN) writeFileSync(path, frenchSpacing(renderAnswerPage(row, related, lang), lang));
      written++;
    }
  }

  console.log(
    `${DRY_RUN ? '[dry run] would write' : 'Wrote'} ${written} answer page(s)` +
      (skippedExisting ? ` (${skippedExisting} regenerated)` : '') +
      (skippedProtected.length ? `, skipped ${skippedProtected.length} hand-authored file(s): ${skippedProtected.join(', ')}` : '')
  );

  console.log('Skipped audience-page generation — no audience field exists in the schema (see PIPELINE-GAP-AUDIT.md).');
  console.log(`Done. ${written} answer page(s).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
