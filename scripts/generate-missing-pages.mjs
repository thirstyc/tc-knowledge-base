import { TOPICS } from '../topics.config.mjs';

const DRY_RUN = process.argv.includes('--dry-run');
// Deliberately overwrite a hand-authored file this one time. Not for
// routine use — after a --force run the file carries GENERATED_MARKER and
// every future run overwrites it normally, without needing the flag again.
const FORCE = process.argv.includes('--force');

