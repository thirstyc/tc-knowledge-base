// Marks a file as safe to regenerate/overwrite on the next run. Hand-authored
// files (like answer-grenache-alcohol-tannin.html) never carry this, so a
// slug collision with one is refused instead of silently clobbering it.
const GENERATED_MARKER = '<!-- Generated by generate-missing-pages.mjs — do not hand-edit -->';

const DIFFICULTY_LABELS_FR = { Beginner: 'Débutant', Intermediate: 'Intermédiaire' };

function hreflangAlternates(path) {
  return [
    { hreflang: 'en', href: `${BASE_URL}/${path}` },
    { hreflang: 'fr', href: `${BASE_URL}/fr/${path}` },
    { hreflang: 'x-default', href: `${BASE_URL}/${path}` },
  ];
}

// content/sectionTitle are whichever language's row is being rendered;
// effectiveKeywordPattern() unions each topic's English and French phrasing
// (see topics.config.mjs) so a single test matches either. topic.frReady
// guards linking a French page at a topic with no French content yet --
// not expected once translation is complete, but kept defensive.
// The answer's topic is the grape or region it mentions first (the
// question comes first in content, so one named in the question wins).
// Wine-science topics (tannins, oak, ...) are concepts most answers touch in
// passing, so they only win when no grape or region is mentioned. TOPICS
// order only breaks ties between patterns matching at the same position.
function bestTopicIn(text) {
  let best = null;
  for (const topic of TOPICS) {
    const match = new RegExp(effectiveKeywordPattern(topic), 'i').exec(text);
    if (!match) continue;
    const rank = topic.kind === 'enology' ? 1 : 0;
    if (!best || rank < best.rank || (rank === best.rank && match.index < best.index)) {
      best = { topic, index: match.index, rank };
    }
  }
  return best;
}

// Topics that list answers by source_doc prefix (topics.config.mjs) claim
// those answers outright.
function topicBySourceDoc(sourceDoc) {
  return TOPICS.find((t) => t.sourceDocPrefixes?.some((prefix) => (sourceDoc || '').startsWith(prefix)));
}

function resolveTopicLink(content, sectionTitle, lang, sourceDoc) {
  // A topic named in the question itself is what the answer is about
  // ("Best natural wine?"), even if a grape or region comes up first in
  // the body; otherwise fall back to the whole answer.
  // Precedence: a topic named in the question ("Best natural wine?" is
  // about natural wine), then a topic that claims the answer by source_doc
  // prefix, then the first grape/region/concept mentioned in the body.
  const claimed = topicBySourceDoc(sourceDoc);
  const best =
    bestTopicIn(deriveQuestion(content || '')) ??
    (claimed ? { topic: claimed } : null) ??
    bestTopicIn(`${content || ''} ${sectionTitle || ''}`);
  if (best) {
    const { topic } = best;
    const label = lang === 'fr' ? topic.topicNameFr ?? topic.topicName : topic.topicName;
    const href = lang === 'fr' && !topic.frReady ? `../topic-${topic.slug}.html` : `topic-${topic.slug}.html`;
    return { href, label };
  }
  // topics.html was removed as duplicate content (grapes.html/regions.html/
  // guides.html are the real browse destinations now); fall back to the
  // general answers index rather than a page that no longer exists. No
  // fr/answers.html exists yet, so the French fallback points at the
  // English page one level up.
  return lang === 'fr' ? { href: '../answers.html', label: 'Réponses' } : { href: 'answers.html', label: 'Answers' };
}

// Longer answers use blank lines between paragraphs and the same small
// Markdown subset as guides (lists, bold); one-line answers render exactly
// as before (a single <p>).
function answerParagraphs(answerBody) {
  return renderMarkdown(answerBody)
    .split('\n')
    .map((line) => `          ${line}`)
    .join('\n');
}

function renderAnswerPage(row, related, lang) {
  const isFr = lang === 'fr';
  const slugPath = answerPagePath(row.source_doc);
  const path = isFr ? `fr/${slugPath}` : slugPath;
  const question = deriveQuestion(row.content);
  const answerBody = row.content.slice(question.length).trim();
  const topic = resolveTopicLink(row.content, row.section_title, lang, row.source_doc);
  const difficultySlug = row.section_title === 'Beginner' ? 'beginner' : 'intermediate';
  const difficultyLabel = isFr ? DIFFICULTY_LABELS_FR[row.section_title] ?? row.section_title : row.section_title;
  const ap = assetPrefixFor(lang);

  const t = {
    home: isFr ? 'Accueil' : 'Home',
    answers: isFr ? 'Réponses' : 'Answers',
    topic: isFr ? 'Sujet' : 'Topic',
    difficulty: isFr ? 'Difficulté' : 'Difficulty',
    shortAnswer: isFr ? 'Réponse courte' : 'Short Answer',
    keepGoing: isFr ? 'Continuer' : 'Keep Going',
    readAnswer: isFr ? 'Lire la réponse' : 'Read The Answer',
  };

  const relatedCards = related
    .map((r) => {
      const q = deriveQuestion(r.content);
      const bodyPreview = r.content.slice(q.length).trim().split(/(?<=[.!?])\s+/).slice(0, 1).join(' ');
      return `          <a class="card" href="${answerPagePath(r.source_doc)}">
            <span class="card-meta">${escapeHtml(r.chunk_type.toUpperCase())}</span>
            <span class="card-title sm">${escapeHtml(q)}</span>
            <p>${escapeHtml(bodyPreview)}</p>
            <span class="more">${t.readAnswer} &rarr;</span>
          </a>`;
    })
    .join('\n');

  return [
    renderHead({
      title: `${escapeHtml(question)} — Thirsty Cunt`,
      description: escapeHtml(answerBody.replace(/\s+/g, ' ').split(/(?<=[.!?])\s+/).slice(0, 2).join(' ')),
      lang,
      assetPrefix: ap,
      alternates: hreflangAlternates(slugPath),
      jsonLd: [faqPageSchema({ url: path, faqs: [{ question, answer: answerBody }], lang })],
    }),
    GENERATED_MARKER,
    renderHeader({
      currentNav: 'answers.html',
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${slugPath}`,
      enHref: isFr ? `../${slugPath}` : null,
    }),
    `  <main class="has-hero">
${renderHeroBand({
  breadcrumb: `<a href="${ap}index.html">${t.home}</a> / <a href="${ap}answers.html">${t.answers}</a> / ${escapeHtml(question)}`,
  eyebrow: row.source_doc.toUpperCase(),
  title: question,
  variant: 'answer',
})}
    <div class="wrap">
      <article class="sheet">
        <div class="meta-bar">
          <div><p class="k">${t.topic}</p><p class="v"><a href="${topic.href}">${escapeHtml(topic.label)}</a></p></div>
          <div><p class="k">${t.difficulty}</p><p class="v"><a href="difficulty-${difficultySlug}.html">${escapeHtml(difficultyLabel)}</a></p></div>
        </div>

        <div class="short-answer">
          <p class="k">${t.shortAnswer}</p>
${answerParagraphs(answerBody)}
        </div>
      </article>

      ${related.length > 0 ? `<section style="margin-top: 80px">
        <p class="list-head">${t.keepGoing}</p>
        <div class="grid answers-3" style="margin-top: 28px">
${relatedCards}
        </div>
      </section>` : ''}
    </div>
  </main>`,
    renderFooter({
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${slugPath}`,
      enHref: isFr ? `../${slugPath}` : null,
    }),
    `</body>\n</html>\n`,
  ].join('\n');
}

function renderDifficultyPage(difficultyLabelEn, slug, rows, lang) {
  const isFr = lang === 'fr';
  const path = `difficulty-${slug}.html`;
  const ap = assetPrefixFor(lang);
  const difficultyLabel = isFr ? DIFFICULTY_LABELS_FR[difficultyLabelEn] ?? difficultyLabelEn : difficultyLabelEn;

  const t = {
    home: isFr ? 'Accueil' : 'Home',
    answers: isFr ? 'Réponses' : 'Answers',
    eyebrow: isFr ? 'Difficulté' : 'Difficulty',
    lede: isFr
      ? "Le niveau de connaissances qu'une réponse suppose déjà. Commencez où vous voulez."
      : 'How much groundwork an answer assumes. Start anywhere.',
    beginner: isFr ? 'Débutant' : 'Beginner',
    intermediate: isFr ? 'Intermédiaire' : 'Intermediate',
    answerWord: isFr ? 'Réponse' : 'Answer',
  };

  const rowItems = rows
    .map(
      (r) => `      <a class="row-item" href="${answerPagePath(r.source_doc)}">
        <span class="id">${escapeHtml(r.source_doc.toUpperCase())}</span>
        <span class="t">${escapeHtml(deriveQuestion(r.content))}</span>
        <span class="k">${escapeHtml(r.chunk_type.toUpperCase())}</span>
      </a>`
    )
    .join('\n');

  const description = isFr
    ? `${rows.length} réponses écrites à un niveau ${difficultyLabel.toLowerCase()}.`
    : `${rows.length} answers written at ${difficultyLabelEn.toLowerCase()} depth.`;
  const schema = collectionPageSchema({
    name: isFr ? `Réponses ${difficultyLabel}` : `${difficultyLabelEn} Answers`,
    description,
    url: isFr ? `fr/${path}` : path,
    items: rows.map((r) => ({
      name: deriveQuestion(r.content),
      url: `${isFr ? 'fr/' : ''}${answerPagePath(r.source_doc)}`,
    })),
    lang,
  });

  return [
    renderHead({
      title: isFr
        ? `Réponses ${difficultyLabel} — Thirsty Cunt`
        : `${difficultyLabelEn} Answers — Thirsty Cunt Knowledge Base`,
      description,
      lang,
      assetPrefix: ap,
      alternates: hreflangAlternates(path),
      jsonLd: [schema],
    }),
    GENERATED_MARKER,
    renderHeader({
      currentNav: 'answers.html',
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${path}`,
      enHref: isFr ? `../${path}` : null,
    }),
    `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="${ap}index.html">${t.home}</a> / <a href="${ap}answers.html">${t.answers}</a> / ${t.eyebrow}</p>
      <p class="eyebrow">${t.eyebrow}</p>
      <h1 class="page-title">${isFr ? `Réponses ${difficultyLabel}` : `${difficultyLabelEn} Answers`}</h1>
      <p class="lede sm" style="margin-bottom: 40px">${t.lede}</p>

      <div class="chip-row" style="margin-bottom: 52px">
        <a class="chip" href="difficulty-beginner.html"${slug === 'beginner' ? ' aria-current="page"' : ''}>${t.beginner}</a>
        <a class="chip" href="difficulty-intermediate.html"${slug === 'intermediate' ? ' aria-current="page"' : ''}>${t.intermediate}</a>
      </div>

      <p class="list-head">${rows.length} ${t.answerWord}${rows.length !== 1 ? 's' : ''}</p>
${rowItems}
    </div>
  </main>`,
    renderFooter({
      lang,
      assetPrefix: ap,
      frHref: isFr ? null : `fr/${path}`,
      enHref: isFr ? `../${path}` : null,
    }),
    `</body>\n</html>\n`,
  ].join('\n');
}

function isSafeToWrite(path) {
  if (FORCE) return true;
  if (!existsSync(path)) return true;
  return readFileSync(path, 'utf8').includes(GENERATED_MARKER);
}

async function main() {
  const fetchedRows = await fetchAllRows(() =>
    supabase
      .from('knowledge_chunks')
      .select('id, content, source_doc, section_title, chunk_type, lang')
      .in('chunk_type', ['qa', 'region-qa'])
      .eq('status', 'published')
      // Without an explicit order, .range() pages can skip or repeat rows,
      // and list order shifts whenever a row is edited.
      .order('id')
  );

  // Rows whose page is listed in redirects.config.mjs are retired: no page,
  // and no links to them from related cards or difficulty archives.
  const pagePathFor = (row) => `${row.lang === 'fr' ? 'fr/' : ''}${answerPagePath(row.source_doc)}`;
  const retired = fetchedRows.filter((row) => pagePathFor(row) in REDIRECTS);
  const allRows = fetchedRows.filter((row) => !(pagePathFor(row) in REDIRECTS));
  if (retired.length) console.log(`Skipped ${retired.length} redirected row(s): ${retired.map(pagePathFor).join(', ')}`);

  mkdirSync('fr', { recursive: true });

  let written = 0;
  let skippedExisting = 0;
  const skippedProtected = [];

  for (const lang of ['en', 'fr']) {
    const rows = allRows.filter((r) => r.lang === lang);

    for (const row of rows) {
      const path = pagePathFor(row);

      if (!isSafeToWrite(path)) {
        skippedProtected.push(path);
        continue;
      }
      if (existsSync(path)) {
        skippedExisting++;
        // Still regenerate — content may have changed since last run.
      }

      // 3 related rows: same chunk_type and language, nearest by id, excluding self.
      const related = rows
        .filter((r) => r.chunk_type === row.chunk_type && r.id !== row.id)
        .sort((a, b) => Math.abs(a.id - row.id) - Math.abs(b.id - row.id))
        .slice(0, 3);

      if (!DRY_RUN) writeFileSync(path, renderAnswerPage(row, related, lang));
      written++;
    }
  }

  console.log(
    `${DRY_RUN ? '[dry run] would write' : 'Wrote'} ${written} answer page(s)` +
      (skippedExisting ? ` (${skippedExisting} regenerated)` : '') +
      (skippedProtected.length ? `, skipped ${skippedProtected.length} hand-authored file(s): ${skippedProtected.join(', ')}` : '')
  );

  // Difficulty archives — only for (language, label) combos that actually have rows.
  let difficultyWritten = 0;
  for (const lang of ['en', 'fr']) {
    const rows = allRows.filter((r) => r.lang === lang);
    const byDifficulty = { Beginner: [], Intermediate: [] };
    for (const row of rows) {
      if (byDifficulty[row.section_title]) byDifficulty[row.section_title].push(row);
    }

    for (const [label, slug] of [['Beginner', 'beginner'], ['Intermediate', 'intermediate']]) {
      const path = lang === 'fr' ? `fr/difficulty-${slug}.html` : `difficulty-${slug}.html`;
      const matched = byDifficulty[label];
      if (matched.length === 0) {
        console.log(`Skipped ${path} — no ${lang} rows with that difficulty exist yet.`);
        continue;
      }
      if (!isSafeToWrite(path)) {
        console.log(`Skipped ${path} — exists and is hand-authored, not generator output.`);
        continue;
      }
      if (!DRY_RUN) writeFileSync(path, renderDifficultyPage(label, slug, matched, lang));
      difficultyWritten++;
      console.log(`${DRY_RUN ? '[dry run] would write' : 'Wrote'} ${path} (${matched.length} answers)`);
    }
  }

  console.log('Skipped audience-page generation — no audience field exists in the schema (see PIPELINE-GAP-AUDIT.md).');
  console.log(`Done. ${written} answer page(s), ${difficultyWritten} difficulty page(s).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
