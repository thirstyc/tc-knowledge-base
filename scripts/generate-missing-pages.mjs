// Marks a file as safe to regenerate/overwrite on the next run. Hand-authored
// files (like answer-grenache-alcohol-tannin.html) never carry this, so a
// slug collision with one is refused instead of silently clobbering it.
const GENERATED_MARKER = '<!-- Generated by generate-missing-pages.mjs — do not hand-edit -->';

function answerSlug(sourceDoc) {
  // qa-* and qa-region-* source_docs are already readable identifiers
  // (e.g. "qa-assyrtiko-region", "qa-region-georgia-style-2"); just strip
  // the leading "qa-" so the URL isn't stuttering ("answer-qa-...html").
  const stripped = sourceDoc.replace(/^qa-/, '');
  return slugify(stripped);
}

function resolveTopicLink(content, sectionTitle) {
  const haystack = `${content || ''} ${sectionTitle || ''}`;
  for (const topic of TOPICS) {
    const pattern = topic.keywordPattern ?? topic.topicName.toLowerCase();
    if (new RegExp(pattern, 'i').test(haystack)) {
      return { href: `topic-${topic.slug}.html`, label: topic.topicName };
    }
  }
  // topics.html was removed as duplicate content (grapes.html/regions.html/
  // guides.html are the real browse destinations now); fall back to the
  // general answers index rather than a page that no longer exists.
  return { href: 'answers.html', label: 'Answers' };
}

function renderAnswerPage(row, related) {
  const question = deriveQuestion(row.content);
  const answerBody = row.content.slice(question.length).trim();
  const topic = resolveTopicLink(row.content, row.section_title);
  const difficultyHref = row.section_title === 'Beginner' ? 'difficulty-beginner.html' : 'difficulty-intermediate.html';

  const relatedCards = related
    .map((r) => {
      const q = deriveQuestion(r.content);
      const bodyPreview = r.content.slice(q.length).trim().split(/(?<=[.!?])\s+/).slice(0, 1).join(' ');
      return `          <a class="card" href="answer-${answerSlug(r.source_doc)}.html">
            <span class="card-meta">${escapeHtml(r.chunk_type.toUpperCase())}</span>
            <span class="card-title sm">${escapeHtml(q)}</span>
            <p>${escapeHtml(bodyPreview)}</p>
            <span class="more">Read The Answer &rarr;</span>
          </a>`;
    })
    .join('\n');

  return [
    renderHead({
      title: `${escapeHtml(question)} — Thirsty Cunt`,
      description: escapeHtml(answerBody.split(/(?<=[.!?])\s+/).slice(0, 2).join(' ')),
    }),
    GENERATED_MARKER,
    renderHeader({ currentNav: 'answers.html' }),
    `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="index.html">Home</a> / <a href="answers.html">Answers</a> / ${escapeHtml(question)}</p>

      <article class="sheet">
        <p class="ans-id">${escapeHtml(row.source_doc.toUpperCase())}</p>
        <h1>${escapeHtml(question)}</h1>

        <div class="meta-bar">
          <div><p class="k">Topic</p><p class="v"><a href="${topic.href}">${escapeHtml(topic.label)}</a></p></div>
          <div><p class="k">Difficulty</p><p class="v"><a href="${difficultyHref}">${escapeHtml(row.section_title)}</a></p></div>
        </div>

        <div class="short-answer">
          <p class="k">Short Answer</p>
          <p>${escapeHtml(answerBody)}</p>
        </div>
      </article>

      ${related.length > 0 ? `<section style="margin-top: 80px">
        <p class="list-head">Keep Going</p>
        <div class="grid answers-3" style="margin-top: 28px">
${relatedCards}
        </div>
      </section>` : ''}
    </div>
  </main>`,
    renderFooter(),
    `</body>\n</html>\n`,
  ].join('\n');
}

function renderDifficultyPage(difficultyLabel, slug, rows) {
  const rowItems = rows
    .map(
      (r) => `      <a class="row-item" href="answer-${answerSlug(r.source_doc)}.html">
        <span class="id">${escapeHtml(r.source_doc.toUpperCase())}</span>
        <span class="t">${escapeHtml(deriveQuestion(r.content))}</span>
        <span class="k">${escapeHtml(r.chunk_type.toUpperCase())}</span>
      </a>`
    )
    .join('\n');

  return [
    renderHead({
      title: `${difficultyLabel} Answers — Thirsty Cunt Knowledge Base`,
      description: `${rows.length} answers written at ${difficultyLabel.toLowerCase()} depth.`,
    }),
    GENERATED_MARKER,
    renderHeader({ currentNav: 'answers.html' }),
    `  <main>
    <div class="wrap">
      <p class="breadcrumb"><a href="index.html">Home</a> / <a href="answers.html">Answers</a> / Difficulty</p>
      <p class="eyebrow">Difficulty</p>
      <h1 class="page-title">${difficultyLabel} Answers</h1>
      <p class="lede sm" style="margin-bottom: 40px">How much groundwork an answer assumes. Start anywhere.</p>

      <div class="chip-row" style="margin-bottom: 52px">
        <a class="chip" href="difficulty-beginner.html"${slug === 'beginner' ? ' aria-current="page"' : ''}>Beginner</a>
        <a class="chip" href="difficulty-intermediate.html"${slug === 'intermediate' ? ' aria-current="page"' : ''}>Intermediate</a>
      </div>

      <p class="list-head">${rows.length} Answer${rows.length !== 1 ? 's' : ''}</p>
${rowItems}
    </div>
  </main>`,
    renderFooter(),
    `</body>\n</html>\n`,
  ].join('\n');
}

function isSafeToWrite(path) {
  if (FORCE) return true;
  if (!existsSync(path)) return true;
  return readFileSync(path, 'utf8').includes(GENERATED_MARKER);
}

async function main() {
  const rows = await fetchAllRows(() =>
    supabase
      .from('knowledge_chunks')
      .select('id, content, source_doc, section_title, chunk_type')
      .in('chunk_type', ['qa', 'region-qa'])
      .eq('status', 'published')
  );

  let written = 0;
  let skippedExisting = 0;
  const skippedProtected = [];

  for (let i = 0; i < rows.length; i++) {
    const row = rows[i];
    const path = `answer-${answerSlug(row.source_doc)}.html`;

    if (!isSafeToWrite(path)) {
      skippedProtected.push(path);
      continue;
    }
    if (existsSync(path)) {
      skippedExisting++;
      // Still regenerate — content may have changed since last run.
    }

    // 3 related rows: same chunk_type, nearest by id, excluding self.
    const related = rows
      .filter((r) => r.chunk_type === row.chunk_type && r.id !== row.id)
      .sort((a, b) => Math.abs(a.id - row.id) - Math.abs(b.id - row.id))
      .slice(0, 3);

    if (!DRY_RUN) writeFileSync(path, renderAnswerPage(row, related));
    written++;
  }

  console.log(
    `${DRY_RUN ? '[dry run] would write' : 'Wrote'} ${written} answer page(s)` +
      (skippedExisting ? ` (${skippedExisting} regenerated)` : '') +
      (skippedProtected.length ? `, skipped ${skippedProtected.length} hand-authored file(s): ${skippedProtected.join(', ')}` : '')
  );

  // Difficulty archives — only for labels that actually have rows.
  const byDifficulty = { Beginner: [], Intermediate: [] };
  for (const row of rows) {
    if (byDifficulty[row.section_title]) byDifficulty[row.section_title].push(row);
  }

  let difficultyWritten = 0;
  for (const [label, slug] of [['Beginner', 'beginner'], ['Intermediate', 'intermediate']]) {
    const path = `difficulty-${slug}.html`;
    const matched = byDifficulty[label];
    if (matched.length === 0) {
      console.log(`Skipped difficulty-${slug}.html — no rows with that difficulty exist yet.`);
      continue;
    }
    if (!isSafeToWrite(path)) {
      console.log(`Skipped ${path} — exists and is hand-authored, not generator output.`);
      continue;
    }
    if (!DRY_RUN) writeFileSync(path, renderDifficultyPage(label, slug, matched));
    difficultyWritten++;
    console.log(`${DRY_RUN ? '[dry run] would write' : 'Wrote'} ${path} (${matched.length} answers)`);
  }

  console.log('Skipped audience-page generation — no audience field exists in the schema (see PIPELINE-GAP-AUDIT.md).');
  console.log(`Done. ${written} answer page(s), ${difficultyWritten} difficulty page(s).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
